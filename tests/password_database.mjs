import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {PGlite}=await import(pathToFileURL(process.env.FIELDREADY_TEST_PGLITE||'/tmp/fieldready-sql-test/node_modules/@electric-sql/pglite/dist/index.js').href);
const sql=async name=>readFile(new URL('../supabase/'+name,import.meta.url),'utf8');
test('temporary credentials enforce database access, activation, expiry, role preservation and service-only operations',async()=>{
 const db=new PGlite();
 const admin='11111111-1111-1111-1111-111111111111',owner='22222222-2222-2222-2222-222222222222',created='33333333-3333-3333-3333-333333333333';
 try{
  await db.exec(`
   create role anon;create role authenticated;create role service_role bypassrls;
   create schema auth;create table auth.users(id uuid primary key,email text);
   create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   grant usage on schema auth to authenticated;
   create table fr_profiles(user_id uuid primary key references auth.users(id),email text,display_name text,active boolean default true,role text,updated_at timestamptz);
   create function fr_is_active() returns boolean language sql security definer as $$select exists(select 1 from fr_profiles where user_id=auth.uid() and active)$$;
   create function fr_is_enterprise() returns boolean language sql security definer as $$select exists(select 1 from fr_profiles where user_id=auth.uid() and active and role='enterprise')$$;
   create table fr_memberships(id uuid default gen_random_uuid(),user_id uuid references fr_profiles,scope_type text,scope_value text,parent_scope_value text,created_at timestamptz default now());
   create table fr_account_requests(user_id uuid,email text,status text,requested_role text,reviewed_by uuid,reviewed_at timestamptz,decision_note text);
   create table fr_audit_log(actor uuid,action text,table_name text,record_id uuid);
   create table fr_events(id uuid primary key,majcom text,home_installation_id text,created_by uuid,closed_at timestamptz,deleted_at timestamptz);
   create table fr_event_evaluators(event_id uuid,user_id uuid,unique(event_id,user_id));
   create table fr_evaluator_scopes(evaluator_id uuid,majcom text);
   create table fr_manager_evaluators(manager_id uuid,evaluator_id uuid,majcom text);
   alter table fr_events enable row level security;
   create policy historical_permissive on fr_events for all to authenticated using(true) with check(true);
   grant select,insert,update on fr_events to authenticated;
   grant select on fr_profiles to authenticated;
   create function fr_can_access_event(uuid) returns boolean language sql as $$select fr_is_active()$$;
   create function fr_can_manage_event_scope(text,text,uuid) returns boolean language sql as $$select fr_is_active()$$;
   insert into auth.users values('${admin}','admin@example.invalid'),('${owner}','owner@example.invalid'),('${created}','created@example.invalid');
   insert into fr_profiles(user_id,email,display_name,active,role) values('${admin}','admin@example.invalid','Admin',true,'enterprise'),('${owner}','owner@example.invalid','Owner',true,'evaluator');
   insert into fr_events values('${admin}','ACC','test-base','${owner}',null,null);
   insert into fr_event_evaluators values('${admin}','${owner}');
  `);
  await db.exec(await sql('013_username_login.sql'));
  const account=await sql('002_account_administration.sql');
  await db.exec(account.slice(account.indexOf('create or replace function public.fr_set_user_access'),account.indexOf('-- Audit account governance')));
  await db.exec(await sql('009_manager_evaluator_capability.sql'));
  const before=(await db.query("select 'fr_eligible_evaluators(text,text)'::regprocedure::oid as oid")).rows[0].oid;
  const migration=await sql('014_temporary_passwords.sql');await db.exec(migration);await db.exec(migration);
  assert.equal((await db.query("select 'fr_eligible_evaluators(text,text)'::regprocedure::oid as oid")).rows[0].oid,before);
  const root=async()=>db.exec('reset role;');
  const service=async()=>db.exec('reset role;set role service_role;');
  const auth=async uid=>db.exec(`reset role;set role authenticated;set request.jwt.claim.sub='${uid}';`);
  const profile=async uid=>(await db.query('select * from fr_profiles where user_id=$1',[uid])).rows[0];
  await service();
  await db.query('select fr_create_temporary_profile($1,$2,$3,$4,$5,$6,$7,$8,$9)',[admin,created,'created@example.invalid','Created','nurse.created','program_manager','installation','test-base','ACC']);
  await root();let p=await profile(created);
  assert.equal(p.active,false);assert.equal(p.password_resume_active,true);assert.equal(p.password_change_required,true);
  assert.equal((await db.query('select parent_scope_value from fr_memberships where user_id=$1',[created])).rows[0].parent_scope_value,'ACC');
  await auth(created);
  assert.equal((await db.query('select * from fr_events')).rows.length,0);
  await assert.rejects(db.query('insert into fr_events(id) values(gen_random_uuid())'),/row-level security/);
  await assert.rejects(db.query("select fr_eligible_evaluators('ACC',null)"),/completed password setup/);
  await assert.rejects(db.query('select fr_complete_password_change($1,$2)',[created,p.password_reset_id]),/permission denied/);
  await assert.rejects(db.query('select fr_begin_temporary_password($1,$2)',[admin,owner]),/permission denied/);
  await assert.rejects(db.query('update fr_profiles set password_change_required=false where user_id=$1',[created]),/permission denied/);
  // A normal Enterprise access update cannot bypass the first-login requirement.
  await auth(admin);await db.query('select fr_set_user_access($1,false,$2,$3,$4)',[created,'program_manager','installation','test-base']);
  await root();assert.equal((await profile(created)).password_resume_active,false);
  await service();await assert.rejects(db.query('select fr_complete_password_change($1,$2)',[created,p.password_reset_id]),/changed or expired/);
  await auth(admin);await db.query('select fr_set_user_access($1,true,$2,$3,$4)',[created,'program_manager','installation','test-base']);
  await root();assert.equal((await profile(created)).active,false);
  await service();await db.query('select fr_complete_password_change($1,$2)',[created,p.password_reset_id]);
  await root();p=await profile(created);assert.equal(p.active,true);assert.equal(p.role,'program_manager');
  await auth(created);assert.equal((await db.query('select * from fr_events')).rows.length,1);
  await service();const pending=(await db.query('select fr_begin_temporary_password($1,$2) as result',[admin,owner])).rows[0].result;
  await root();p=await profile(owner);assert.equal(p.active,false);assert.equal(p.username,'fr.'+owner.replaceAll('-',''));
  assert.equal((await db.query('select * from fr_event_evaluators where user_id=$1',[owner])).rows.length,1);
  await service();assert.equal((await db.query('select fr_resolve_login($1) as result',[p.username])).rows[0].result.email,'owner@example.invalid');
  for(let i=0;i<10;i++)assert.ok((await db.query('select fr_password_change_context($1) as result',[owner])).rows[0].result.resetId);
  assert.equal((await db.query('select fr_password_change_context($1) as result',[owner])).rows[0].result.limited,true);
  const fresh=(await db.query('select fr_begin_temporary_password($1,$2) as result',[admin,owner])).rows[0].result;
  await assert.rejects(db.query('select fr_complete_password_change($1,$2)',[owner,pending.resetId]),/changed or expired/);
  await root();await db.query("update fr_profiles set temporary_password_expires_at=now()-interval '1 second' where user_id=$1",[owner]);
  await service();assert.match((await db.query('select fr_password_change_context($1) as result',[owner])).rows[0].result.error,/expired/);
  await assert.rejects(db.query('select fr_begin_temporary_password($1,$2)',[admin,admin]),/own password/);
  await assert.rejects(db.query('select fr_begin_temporary_password($1,$2)',[owner,created]),/Enterprise access/);
  const final=(await db.query('select fr_begin_temporary_password($1,$2) as result',[admin,owner])).rows[0].result;
  await db.query('select fr_complete_password_change($1,$2)',[owner,final.resetId]);
  await root();assert.equal((await profile(owner)).role,'evaluator');assert.equal((await profile(owner)).active,true);
  assert.equal((await db.query("select * from fr_audit_log where action='COMPLETE_PASSWORD_CHANGE'")).rows.length,2);
 }finally{await db.close();}
});
